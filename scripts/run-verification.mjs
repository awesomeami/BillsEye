import { spawnSync } from 'node:child_process';
import { generateKeyPairSync } from 'node:crypto';
import process from 'node:process';
import { log } from 'node:console';

const npmCliPath = process.env.npm_execpath;
const npm = npmCliPath ? process.execPath : process.platform === 'win32' ? 'npm.cmd' : 'npm';
const npmPrefixArgs = npmCliPath ? [npmCliPath] : [];
const runFirestoreTests = process.env.SKIP_FIRESTORE !== '1';
const writeReport = process.argv.includes('--write-report');
const projectId = process.env.FIREBASE_PROJECT_ID ?? 'kharchalens-verify';
const verificationServiceAccount = process.env.FIREBASE_SERVICE_ACCOUNT ?? JSON.stringify({
  type: 'service_account',
  project_id: projectId,
  private_key_id: 'verification-only',
  private_key: generateKeyPairSync('rsa', { modulusLength: 2048 }).privateKey.export({ type: 'pkcs8', format: 'pem' }).toString(),
  client_email: `verification@${projectId}.iam.gserviceaccount.com`,
  client_id: '0',
});

const checks = [
  { name: 'Lint', command: 'lint' },
  { name: 'Type checking', command: 'typecheck' },
  { name: 'Unit tests', command: 'test:unit' },
  ...(runFirestoreTests
    ? [{ name: 'Firestore emulator tests', command: 'test:firestore' }]
    : [{ name: 'Firestore emulator tests', skip: 'SKIP_FIRESTORE=1 (emulator runtime intentionally unavailable)' }]),
  { name: 'Browser journey and accessibility smoke', command: 'test:e2e' },
  { name: 'Production build', command: 'build' },
];

const results = checks.map(check => {
  if ('skip' in check) return { ...check, status: 'Skipped' };
  const startedAt = new Date().toISOString();
  const result = spawnSync(npm, [...npmPrefixArgs, 'run', check.command], {
    cwd: process.cwd(),
    stdio: 'inherit',
    env: {
      ...process.env,
      FIREBASE_SERVICE_ACCOUNT: verificationServiceAccount,
      NODE_OPTIONS: process.env.NODE_OPTIONS ?? '--max-old-space-size=1536',
    },
  });
  return {
    ...check,
    startedAt,
    status: result.status === 0 ? 'Passed' : 'Failed',
    exitCode: result.status ?? 1,
  };
});

const reportLines = [
  '# Verification report',
  '',
  `Generated by \`npm run update-report\` on ${new Date().toISOString()}. This file records the commands this run actually attempted; it does not claim unrun suites passed.`,
  '',
  '| Check | Command | Status |',
  '| --- | --- | --- |',
  ...results.map(result => {
    const command = 'skip' in result ? result.skip : `npm run ${result.command}`;
    const status = result.status === 'Failed' ? `Failed (exit ${result.exitCode})` : result.status;
    return `| ${result.name} | ${command} | ${status} |`;
  }),
  '',
  '## How to interpret a failure',
  '',
  'Start with the first failed command in the workflow log. Run that exact command locally from the repository root. “Skipped” is intentional and states why; it is not a passing result.',
  '',
  '## CI safety',
  '',
  'The browser tests use an in-memory Firebase repository, a mocked Firebase token, a mocked extraction response, and a repository-owned PNG test asset. No Firebase credentials, Gemini keys, or user receipts are used.',
  '',
  '## Current lint budget',
  '',
  'Lint warnings are not permitted. The lint command must complete without warnings before this report can record a successful verification.',
  '',
];

const report = reportLines.join('\n');
if (writeReport) {
  const { writeFileSync } = await import('node:fs');
  const { resolve } = await import('node:path');
  writeFileSync(resolve(process.cwd(), 'TEST_REPORT.md'), report, 'utf8');
} else {
  log(`\nVerification completed without changing TEST_REPORT.md. Run \`npm run update-report\` to refresh the committed report.\n`);
}

if (results.some(result => result.status === 'Failed')) process.exitCode = 1;
